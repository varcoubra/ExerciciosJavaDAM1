public class Main {
    static void main() {

        double m=1, n=2, p=3, q=4, a=5, b=6, x=7, y=8;

        System.out.println(m/n*(p+q));
        System.out.println(m / n + 1);
        System.out.println((m + 1) / n);
        System.out.println(m + n / 1);
        System.out.println( ( x + y ) * ( x + y ) * ( a - b ) );
        System.out.println( Math.pow((x + y), 2) * (a - b) );
    }
}
